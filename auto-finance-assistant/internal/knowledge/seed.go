// SeedBuiltinDocs 导入预置知识库文档。
// 仅在数据库为空（无文档）时执行，避免重复导入。
// 返回导入的文档数。
func SeedBuiltinDocs(ctx context.Context, im *Importer) (int, error) {
	// 检查是否已有文档
	existing, err := storage.ListDocuments(ctx, im.db, "", 1)
	if err != nil {
		return 0, fmt.Errorf("检查现有文档失败: %w", err)
	}
	if len(existing) > 0 {
		return 0, nil // 已有文档，跳过
	}

	count := 0
	for name, content := range BuiltinDocs {
		result, err := im.Import(ctx, strings.NewReader(content), name)
		if err != nil {
			continue // 单个失败不影响其他
		}
		if result.DocumentID != "" && result.Status != "duplicate" {
			// 自动发布
			if err := im.Publish(ctx, result.DocumentID); err == nil {
				count++
			}
		}
	}
	return count, nil
}
