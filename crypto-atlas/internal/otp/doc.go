// Package otp 实现一次性密码本（One-Time Pad）——
// 唯一被信息论证明"绝对安全"的密码（Shannon 1949）。
//
// 更多背景（Shannon 绝对安全证明、为什么实际不实用）见 NOTES.md。
//
// OTP 的教学价值在于把"密码的安全上限"推到极致：只要密钥真随机、
// 与明文等长、只用一次，密文就不含明文的任何信息——破解在物理上不可能。
// 它是密码学里的"北极星"：所有现实里"计算安全"的方案（AES、ChaCha20）
// 都是在"做不到 OTP 那样分发密钥"的妥协下，尽力逼近 OTP 的安全性。
